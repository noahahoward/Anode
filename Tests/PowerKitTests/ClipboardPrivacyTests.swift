import XCTest
@testable import PowerKit

/// What Clipboard History never records: a copy an app marked as not for a history, a copy from a password manager, and a copy
/// from an app the person asked to leave out. The rules read only type strings and an app's id, never the copy itself, and the
/// store applies them again on its own, so a caller that forgot to check still cannot put a password in the history.
final class ClipboardPrivacyTests: XCTestCase {

    private static let secret = "hunter2-correct-horse-battery-staple"
    private let plain = "public.utf8-plain-text"
    private let start = Date(timeIntervalSince1970: 1_800_000_000)

    private var root: URL!
    private var directory: URL { root.appendingPathComponent(ClipboardStore.folderName, isDirectory: true) }

    override func setUpWithError() throws {
        root = URL(fileURLWithPath: NSTemporaryDirectory(), isDirectory: true)
            .appendingPathComponent("com.anode.tests.clipboard-privacy.\(UUID().uuidString)", isDirectory: true)
        try FileManager.default.createDirectory(at: root, withIntermediateDirectories: true)
    }

    override func tearDownWithError() throws {
        if let root { try? FileManager.default.removeItem(at: root) }
    }

    private func makeStore() -> ClipboardStore {
        ClipboardStore(directory: directory,
                       limits: ClipboardStore.Limits(maxEntries: 100, maxEntryBytes: 1_000_000, maxTotalBytes: 10_000_000, maxAge: nil))
    }

    /// A copy of the secret text with these extra types beside it, as an app would put it on the pasteboard.
    private func copy(alsoOfType extra: [String] = [], from app: String? = nil) -> ClipboardSnapshot {
        var reps = [ClipboardRepresentation(item: 0, type: plain, data: Data(Self.secret.utf8))]
        for type in extra { reps.append(ClipboardRepresentation(item: 0, type: type, data: Data("x".utf8))) }
        return ClipboardSnapshot(representations: reps, sourceBundleID: app, sourceName: nil, date: start)
    }

    /// Every file under the root, read, for the one question a privacy test asks: is the secret anywhere on disk.
    private func diskHoldsTheSecret() -> Bool {
        let needle = Data(Self.secret.utf8)
        guard let walker = FileManager.default.enumerator(at: root, includingPropertiesForKeys: [.isRegularFileKey]) else { return false }
        for case let url as URL in walker {
            guard (try? url.resourceValues(forKeys: [.isRegularFileKey]))?.isRegularFile == true,
                  let data = try? Data(contentsOf: url) else { continue }
            if data.range(of: needle) != nil { return true }
        }
        return false
    }

    // ── The markers an app puts on a copy ───────────────────────────────────

    /// The table is the contract: whatever marker the code knows, a copy carrying it is refused with the word beside it, with
    /// no app and no list to help.
    func testEveryMarkerTheCodeKnowsIsRefusedWithItsOwnWord() {
        XCTAssertFalse(ClipboardPrivacy.markers.isEmpty)
        for (type, word) in ClipboardPrivacy.markers {
            XCTAssertEqual(ClipboardPrivacy.skipReason(types: [type], sourceBundleID: nil, ignoredApps: []), word, type)
        }
    }

    /// The four that matter most, spelled out here so that a marker dropped from the table fails a test: passwords,
    /// restored-a-moment-later copies, copies nobody chose to make, and Universal Clipboard.
    func testTheStandardMarkersAreRefusedWithTheWordsTheLogUses() {
        let expected: [(type: String, word: String)] = [
            ("org.nspasteboard.ConcealedType", "concealed"),
            ("org.nspasteboard.TransientType", "transient"),
            ("org.nspasteboard.AutoGeneratedType", "auto-generated"),
            ("com.apple.is-remote-clipboard", "from another device"),
        ]
        for (type, word) in expected {
            XCTAssertEqual(ClipboardPrivacy.skipReason(types: [type], sourceBundleID: nil, ignoredApps: []), word, type)
        }
    }

    /// A marker is one type among the others on the pasteboard, usually after the text it is about: where it sits does not
    /// matter.
    func testAMarkerAmongOrdinaryTypesStillRefusesTheCopy() {
        let marker = "org.nspasteboard.ConcealedType"
        for types in [[plain, marker], [marker, plain], [plain, "public.html", marker, "public.rtf"]] {
            XCTAssertEqual(ClipboardPrivacy.skipReason(types: types, sourceBundleID: "com.example.Editor", ignoredApps: []),
                           "concealed", "\(types)")
        }
    }

    /// An app with nothing to hide is recorded: no marker, not a manager, not on the list.
    func testACopyWithNoneOfThatHasNoReasonToBeRefused() {
        XCTAssertNil(ClipboardPrivacy.skipReason(types: [plain, "public.html"], sourceBundleID: "com.apple.Safari",
                                                 ignoredApps: ["com.example.Other"]))
        XCTAssertNil(ClipboardPrivacy.skipReason(types: [], sourceBundleID: nil, ignoredApps: []))
        XCTAssertNil(ClipboardPrivacy.skipReason(types: [plain], sourceBundleID: nil, ignoredApps: ["com.example.Other"]))
    }

    /// Only the nspasteboard.org family is a marker that must never be kept; an ordinary type that happens to be near it in
    /// the alphabet is not.
    func testAMarkerTypeIsTheNspasteboardPrefixAndNothingElse() {
        XCTAssertTrue(ClipboardTypes.isMarker("org.nspasteboard.ConcealedType"))
        XCTAssertTrue(ClipboardTypes.isMarker("org.nspasteboard.source"))
        XCTAssertFalse(ClipboardTypes.isMarker("public.utf8-plain-text"))
        XCTAssertFalse(ClipboardTypes.isMarker("org.nspasteboardx.thing"))
        XCTAssertFalse(ClipboardTypes.isMarker("org.nspasteboard"))
        XCTAssertFalse(ClipboardTypes.isMarker(""))
    }

    // ── Password managers ───────────────────────────────────────────────────

    /// Whatever a password manager copies is never recorded, whether or not it remembered to mark the copy.
    func testEveryKnownPasswordManagerIsRefusedByItsExactId() {
        let spelledOut = [
            "com.apple.Passwords", "com.apple.keychainaccess", "com.1password.1password", "com.agilebits.onepassword7",
            "com.agilebits.onepassword-osx", "com.bitwarden.desktop", "com.dashlane.dashlanephonefinal", "com.lastpass.LastPass",
            "org.keepassxc.keepassxc", "in.sinew.Enpass-Desktop", "com.nordsec.nordpass", "me.proton.pass.electron",
        ]
        for id in spelledOut {
            XCTAssertTrue(ClipboardPrivacy.passwordManagers.contains(id), "\(id) is in the list")
            XCTAssertTrue(ClipboardPrivacy.isPasswordManager(id), id)
            XCTAssertEqual(ClipboardPrivacy.skipReason(types: [plain], sourceBundleID: id, ignoredApps: []), "password manager", id)
        }
        for id in ClipboardPrivacy.passwordManagers {
            XCTAssertTrue(ClipboardPrivacy.isPasswordManager(id), id)
        }
    }

    /// Three of the exact ids have no manager's name in them (Apple's two, and Proton Pass), so the list alone has to catch
    /// them.
    func testTheManagersWithNoNameInTheirIdAreCaughtByTheList() {
        for id in ["com.apple.Passwords", "com.apple.keychainaccess", "me.proton.pass.electron"] {
            XCTAssertTrue(ClipboardPrivacy.isPasswordManager(id), id)
        }
    }

    /// A manager the list does not know by id (a fork, a beta, another vendor's build) is caught by its name.
    func testAnIdThatHasAPasswordManagersNameInItIsOneToo() {
        XCTAssertTrue(ClipboardPrivacy.isPasswordManager("com.example.MyBitwardenFork"))
        for fragment in ["1password", "bitwarden", "keepass", "lastpass", "dashlane", "enpass", "nordpass"] {
            XCTAssertTrue(ClipboardPrivacy.isPasswordManager("com.example.\(fragment).beta"), fragment)
            XCTAssertEqual(ClipboardPrivacy.skipReason(types: [plain], sourceBundleID: "com.example.\(fragment)", ignoredApps: []),
                           "password manager", fragment)
        }
    }

    /// Bundle ids are written in mixed case ("com.lastpass.LastPass"); the name inside one is found whichever way it is spelled.
    func testTheNameInAnIdIsFoundWhateverTheCase() {
        XCTAssertTrue(ClipboardPrivacy.isPasswordManager("COM.EXAMPLE.BITWARDEN"))
        XCTAssertTrue(ClipboardPrivacy.isPasswordManager("com.example.KeePassX"))
        XCTAssertTrue(ClipboardPrivacy.isPasswordManager("com.example.LASTPASS-helper"))
    }

    /// Refusing too much would make the history useless: everyday apps are not managers.
    func testOrdinaryAppsAreNotPasswordManagers() {
        for id in ["com.apple.Safari", "com.apple.TextEdit", "com.apple.Terminal", "com.apple.Notes", "com.apple.mail",
                   "com.microsoft.VSCode", "com.googlecode.iterm2", "org.mozilla.firefox", "com.tinyspeck.slackmacgap"] {
            XCTAssertFalse(ClipboardPrivacy.isPasswordManager(id), id)
            XCTAssertNil(ClipboardPrivacy.skipReason(types: [plain], sourceBundleID: id, ignoredApps: []), id)
        }
    }

    /// An app the Mac could not name, and an id that is empty, are not a manager: nothing is known against them, and a
    /// copy from an unknown app is an ordinary copy.
    func testNoAppAndAnEmptyIdAreNotPasswordManagers() {
        XCTAssertFalse(ClipboardPrivacy.isPasswordManager(nil))
        XCTAssertFalse(ClipboardPrivacy.isPasswordManager(""))
        XCTAssertNil(ClipboardPrivacy.skipReason(types: [plain], sourceBundleID: nil, ignoredApps: []))
        XCTAssertNil(ClipboardPrivacy.skipReason(types: [plain], sourceBundleID: "", ignoredApps: []))
    }

    // ── The person's own list ───────────────────────────────────────────────

    /// An app on the list is refused, and only that app: the list names ids, not families of them.
    func testTheOwnersIgnoredListRefusesThatAppAndOnlyThatApp() {
        let list: Set<String> = ["com.example.Vault"]
        XCTAssertEqual(ClipboardPrivacy.skipReason(types: [plain], sourceBundleID: "com.example.Vault", ignoredApps: list), "ignored app")
        XCTAssertNil(ClipboardPrivacy.skipReason(types: [plain], sourceBundleID: "com.example.VaultPro", ignoredApps: list))
        XCTAssertNil(ClipboardPrivacy.skipReason(types: [plain], sourceBundleID: "com.example", ignoredApps: list))
        XCTAssertNil(ClipboardPrivacy.skipReason(types: [plain], sourceBundleID: nil, ignoredApps: list), "no app named, nothing to ignore")
        XCTAssertNil(ClipboardPrivacy.skipReason(types: [plain], sourceBundleID: "com.example.Vault", ignoredApps: []), "not on the list")
    }

    /// The list is added to the managers and takes none away: with no list, an unrelated list, or the manager itself on the
    /// list, a password manager's copy is refused.
    func testTheIgnoredListNeverUnRefusesAPasswordManager() {
        for id in ClipboardPrivacy.passwordManagers.union(["com.example.MyBitwardenFork"]) {
            XCTAssertEqual(ClipboardPrivacy.skipReason(types: [plain], sourceBundleID: id, ignoredApps: []), "password manager", id)
            XCTAssertEqual(ClipboardPrivacy.skipReason(types: [plain], sourceBundleID: id, ignoredApps: ["com.example.Other"]),
                           "password manager", id)
            XCTAssertNotNil(ClipboardPrivacy.skipReason(types: [plain], sourceBundleID: id, ignoredApps: [id]), id)
        }
    }

    // ── The store is the last line of defence ───────────────────────────────

    /// The caller here never asks the rules anything: it hands the copy to the store, which refuses a concealed one itself.
    func testTheStoreRefusesAConcealedCopyItselfWithoutBeingTold() {
        let store = makeStore()
        let result = store.add(copy(alsoOfType: ["org.nspasteboard.ConcealedType"], from: "com.example.Editor"))
        XCTAssertEqual(result, .skipped("concealed"))
        XCTAssertTrue(store.entries.isEmpty)
        XCTAssertFalse(diskHoldsTheSecret())
    }

    /// Every marker in the table, through the store: each is refused with its word.
    func testTheStoreRefusesEveryMarkerWithItsWord() {
        let store = makeStore()
        for (type, word) in ClipboardPrivacy.markers {
            XCTAssertEqual(store.add(copy(alsoOfType: [type])), .skipped(word), type)
        }
        XCTAssertTrue(store.entries.isEmpty)
        XCTAssertFalse(diskHoldsTheSecret())
    }

    /// A password manager that forgot the marker is refused by the store all the same, with the default policy.
    func testTheStoreRefusesAPasswordManagersUnmarkedCopy() {
        let store = makeStore()
        XCTAssertEqual(store.add(copy(from: "com.bitwarden.desktop")), .skipped("password manager"))
        XCTAssertEqual(store.add(copy(from: "com.example.MyBitwardenFork")), .skipped("password manager"))
        XCTAssertTrue(store.entries.isEmpty)
        XCTAssertFalse(diskHoldsTheSecret())
    }

    /// The policy the store is handed is the person's list: the same app is refused with it, and is an ordinary app without.
    func testTheStoreRefusesAnIgnoredAppOnlyWhenThePolicyNamesIt() throws {
        let store = makeStore()
        let policy = ClipboardStore.Policy(ignoredApps: ["com.example.Vault"], keepImages: true)
        XCTAssertEqual(store.add(copy(from: "com.example.Vault"), policy: policy), .skipped("ignored app"))
        XCTAssertTrue(store.entries.isEmpty)
        XCTAssertFalse(diskHoldsTheSecret())

        guard case .added = store.add(copy(from: "com.example.Vault")) else { return XCTFail("not on the list, so it is kept") }
        XCTAssertEqual(store.entries.count, 1)
    }

    /// A refused copy writes nothing, not even the folder, and the store carries on taking ordinary copies afterwards.
    func testARefusedCopyLeavesNothingOnDiskAndTheStoreStillWorks() {
        let store = makeStore()
        store.add(copy(alsoOfType: ["org.nspasteboard.ConcealedType"]))
        store.add(copy(from: "com.1password.1password"))
        XCTAssertFalse(FileManager.default.fileExists(atPath: directory.path), "nothing was written for a copy that was refused")

        let ordinary = ClipboardSnapshot(representations: [ClipboardRepresentation(item: 0, type: plain, data: Data("a plain note".utf8))],
                                         sourceBundleID: "com.apple.TextEdit", sourceName: "TextEdit", date: start)
        guard case .added = store.add(ordinary) else { return XCTFail("an ordinary copy is kept") }
        XCTAssertEqual(store.entries.map(\.text), ["a plain note"])
    }
}
